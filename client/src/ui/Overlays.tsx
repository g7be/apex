import { useState } from 'react';
import { game, useGame } from '../state/store.ts';
import { gameServerUrl, identity, net } from '../net/connection.ts';

export function JoinScreen({ onJoin }: { onJoin: () => void }) {
  const manifest = useGame((s) => s.manifest);
  const [name, setName] = useState(identity.savedName());
  const valid = name.trim().length >= 2;
  return (
    <div className="join">
      <div className="join-card">
        <div className="join-kicker">Real-world property simulation</div>
        <h1>Downtown<br />Indianapolis</h1>
        <p>
          Fly over the real streets of downtown Indy, inspect every building, browse procedurally generated floor plans and
          lease property with in-game currency, alongside other players.
        </p>
        <form onSubmit={(e) => { e.preventDefault(); if (valid) { net.connect(name.trim()); onJoin(); } }}>
          <label htmlFor="name">Choose a player name</label>
          <input id="name" autoFocus maxLength={20} value={name} onChange={(e) => setName(e.target.value)} placeholder="e.g. HoosierHank" />
          <button className="btn primary wide" disabled={!valid}>Enter the city</button>
        </form>
        <div className="join-meta">
          {manifest ? `${manifest.stats.buildings.toLocaleString()} real buildings · ${manifest.stats.roads.toLocaleString()} streets & paths` : 'Loading map…'}
          {identity.profile !== 'default' && ` · profile “${identity.profile}”`}
        </div>
        <div className="join-attrib">Map data © OpenStreetMap contributors (ODbL). Interiors, tenants and rents are fictional.</div>
      </div>
    </div>
  );
}

export function LoadingScreen() {
  const loading = useGame((s) => s.loading);
  const connection = useGame((s) => s.connection);
  if (loading.ready && (connection === 'online' || connection === 'solo')) return null;
  const pct = loading.tilesTotal ? Math.round((loading.tilesLoaded / loading.tilesTotal) * 100) : 0;
  return (
    <div className="loading">
      <div className="loading-card">
        <div className="spinner" />
        <div>
          {loading.error ? loading.error : !loading.ready ? `Loading downtown Indianapolis… ${pct}%` : connection === 'offline' ? `Can't reach the game server at ${gameServerUrl()} — retrying…` : 'Connecting to the game server…'}
        </div>
      </div>
    </div>
  );
}

export function Toasts() {
  const toasts = useGame((s) => s.toasts);
  return (
    <div className="toasts">
      {toasts.map((t) => <div key={t.id} className={`toast ${t.kind}`}>{t.text}</div>)}
    </div>
  );
}

export function Help() {
  const open = useGame((s) => s.helpOpen);
  if (!open) return null;
  const rows: [string, string][] = [
    ['Left-drag', 'Pan the map'],
    ['Mouse wheel / + −', 'Zoom in and out (toward the cursor)'],
    ['Right-drag', 'Rotate and tilt the view'],
    ['W A S D / arrows', 'Pan (Shift = faster)'],
    ['Q / E', 'Rotate'],
    ['N', 'Face north'],
    ['Home', 'Back to Monument Circle'],
    ['Click', 'Select a building'],
    ['R', 'Open rooms of the selected building'],
    ['Enter / T', 'Chat'],
    ['Esc', 'Close panels / deselect'],
  ];
  return (
    <div className="modal-backdrop" onPointerDown={(e) => { if (e.target === e.currentTarget) game.set({ helpOpen: false }); }}>
      <div className="dialog wide">
        <div className="dialog-head">
          <h3>Controls</h3>
          <button className="icon-btn" onClick={() => game.set({ helpOpen: false })}>✕</button>
        </div>
        <table className="help-table">
          <tbody>{rows.map(([k, v]) => <tr key={k}><td><kbd>{k}</kbd></td><td>{v}</td></tr>)}</tbody>
        </table>
        <p className="fine">
          Buildings, streets and parks come from OpenStreetMap. Interiors are generated by the game from each footprint and
          are not real floor plans. Rents use fictional in-game currency (₵). Open the game in a second browser profile, a private
          window, or with <code>?profile=2</code> to play as another player.
        </p>
      </div>
    </div>
  );
}

export function Attribution() {
  return (
    <div className="attribution">
      © <a href="https://www.openstreetmap.org/copyright" target="_blank" rel="noreferrer">OpenStreetMap</a> contributors
    </div>
  );
}
